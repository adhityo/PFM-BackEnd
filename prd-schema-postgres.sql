-- ===================== 00001_init_functions.sql =====================
-- +goose Up
-- +goose StatementBegin
-- Tidak butuh extension: gen_random_uuid() sudah bawaan PostgreSQL >= 13,
-- sehingga role migrasi tidak perlu hak CREATE EXTENSION.
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin
DROP FUNCTION IF EXISTS set_updated_at();
-- +goose StatementEnd

-- ===================== 00002_create_file_object.sql =====================
-- Tabel baru (non-legacy): registry metadata file. Kolom *_url legacy diganti *_file_id -> file_object.id
-- +goose Up
-- +goose StatementBegin
CREATE TABLE file_object (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid            UUID NOT NULL DEFAULT gen_random_uuid(),
    storage         VARCHAR(10)  NOT NULL,                  -- 'local' | 's3'
    category        VARCHAR(10)  NOT NULL,                  -- 'image' | 'document'
    bucket          VARCHAR(255),                           -- NULL untuk local
    object_key      VARCHAR(512) NOT NULL,                  -- path relatif / S3 key, dibangkitkan server
    original_name   VARCHAR(255) NOT NULL,                  -- sudah disanitasi
    mime_type       VARCHAR(100) NOT NULL,                  -- hasil deteksi magic bytes
    size_bytes      BIGINT       NOT NULL,
    checksum_sha256 CHAR(64)     NOT NULL,
    status          VARCHAR(20)  NOT NULL DEFAULT 'active', -- 'pending' | 'active' | 'quarantined'
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      VARCHAR(100),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by      VARCHAR(100),
    deleted_at      TIMESTAMPTZ,
    deleted_by      VARCHAR(100),
    CONSTRAINT uq_file_object_uuid UNIQUE (uuid),
    CONSTRAINT ck_file_object_storage  CHECK (storage IN ('local', 's3')),
    CONSTRAINT ck_file_object_category CHECK (category IN ('image', 'document')),
    CONSTRAINT ck_file_object_status   CHECK (status IN ('pending', 'active', 'quarantined')),
    CONSTRAINT ck_file_object_size     CHECK (size_bytes > 0),
    CONSTRAINT ck_file_object_pair     CHECK ((category = 'image' AND storage = 'local')
                                           OR (category = 'document' AND storage = 's3'))
);
CREATE UNIQUE INDEX uq_file_object_location ON file_object (storage, COALESCE(bucket, ''), object_key);
CREATE INDEX idx_file_object_checksum ON file_object (checksum_sha256);
CREATE TRIGGER trg_file_object_updated_at BEFORE UPDATE ON file_object
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin
DROP TABLE IF EXISTS file_object;
-- +goose StatementEnd

