package main

import (
	"fmt"
	"strings"
)

// genSQL renders internal/db/queries/<table>.sql for a CRUD resource.
func genSQL(sp *Spec, t *Table) string {
	camel := sqlcName(sp.Table)
	cols := sp.apiColumns(t)

	sel := []string{"t.id", "t.uuid"}
	var joins []string
	for _, c := range cols {
		sel = append(sel, "t."+c.Name)
	}
	for _, c := range cols {
		if ref, ok := t.FKs[c.Name]; ok {
			alias := "r_" + c.Name
			sel = append(sel, fmt.Sprintf("%s.uuid AS %s_uuid", alias, fkBase(c.Name)))
			joins = append(joins, fmt.Sprintf("LEFT JOIN %s %s ON %s.id = t.%s", ref, alias, alias, c.Name))
		}
	}
	sel = append(sel, "t.created_at", "t.updated_at")
	from := "FROM " + sp.Table + " t"
	if len(joins) > 0 {
		from += "\n" + strings.Join(joins, "\n")
	}

	var where []string
	where = append(where, "t.deleted_at IS NULL")
	if len(sp.Search) > 0 {
		var ors []string
		for _, s := range sp.Search {
			ors = append(ors, fmt.Sprintf("t.%s ILIKE '%%' || sqlc.narg('q') || '%%' ESCAPE '\\'", s))
		}
		where = append(where, "(sqlc.narg('q')::text IS NULL\n       OR "+strings.Join(ors, "\n       OR ")+")")
	}
	for _, c := range cols {
		if _, ok := t.FKs[c.Name]; ok {
			where = append(where, fmt.Sprintf("(sqlc.narg('%[1]s')::bigint IS NULL OR t.%[1]s = sqlc.narg('%[1]s'))", c.Name))
		}
	}
	whereSQL := "WHERE " + strings.Join(where, "\n  AND ")

	var order []string
	for _, s := range append(append([]string{}, sp.Sorts...), "created_at") {
		order = append(order,
			fmt.Sprintf("CASE WHEN sqlc.arg('sort')::text = '%[1]s' THEN t.%[1]s END ASC", s),
			fmt.Sprintf("CASE WHEN sqlc.arg('sort')::text = '-%[1]s' THEN t.%[1]s END DESC", s))
	}
	order = append(order, "t.id DESC")

	var b strings.Builder
	b.WriteString("-- Code generated by cmd/scaffold; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "-- name: Get%sByUUID :one\nSELECT %s\n%s\nWHERE t.uuid = $1 AND t.deleted_at IS NULL;\n\n",
		camel, strings.Join(sel, ", "), from)
	fmt.Fprintf(&b, "-- name: List%s :many\nSELECT %s\n%s\n%s\nORDER BY\n  %s\nLIMIT sqlc.arg('limit') OFFSET sqlc.arg('offset');\n\n",
		camel, strings.Join(sel, ", "), from, whereSQL, strings.Join(order, ",\n  "))
	fmt.Fprintf(&b, "-- name: Count%s :one\nSELECT count(*) FROM %s t\n%s;\n\n", camel, sp.Table, whereSQL)

	// Create / update.
	var insCols, insVals, sets []string
	for _, c := range cols {
		switch {
		case sp.isSnapshot(c.Name):
			snap := sp.Snapshot[c.Name]
			expr := fmt.Sprintf("(SELECT s.%s FROM %s s WHERE s.id = sqlc.narg('%s'))", snap.RefColumn, t.FKs[snap.FKColumn], snap.FKColumn)
			insCols, insVals = append(insCols, c.Name), append(insVals, expr)
			sets = append(sets, c.Name+" = "+expr)
		case sp.writable(c):
			v := fmt.Sprintf("sqlc.narg('%s')", c.Name)
			if !c.Nullable {
				v = fmt.Sprintf("sqlc.arg('%s')", c.Name)
			}
			insCols, insVals = append(insCols, c.Name), append(insVals, v)
			sets = append(sets, c.Name+" = "+v)
		}
	}
	insCols = append([]string{"uuid"}, append(insCols, "created_by", "updated_by")...)
	insVals = append([]string{"sqlc.arg('uuid')"}, append(insVals, "sqlc.arg('actor')", "sqlc.arg('actor')")...)
	sets = append(sets, "updated_by = sqlc.arg('actor')")

	fmt.Fprintf(&b, "-- name: Create%s :one\nINSERT INTO %s (%s)\nVALUES (%s)\nRETURNING uuid;\n\n",
		camel, sp.Table, strings.Join(insCols, ", "), strings.Join(insVals, ",\n        "))
	fmt.Fprintf(&b, "-- name: Update%s :execrows\nUPDATE %s t\nSET %s\nWHERE t.uuid = sqlc.arg('uuid') AND t.updated_at = sqlc.arg('expected_updated_at') AND t.deleted_at IS NULL;\n\n",
		camel, sp.Table, strings.Join(sets, ",\n    "))
	fmt.Fprintf(&b, "-- name: SoftDelete%s :execrows\nUPDATE %s t\nSET deleted_at = now(), deleted_by = sqlc.arg('actor')\nWHERE t.uuid = sqlc.arg('uuid') AND t.updated_at = sqlc.arg('expected_updated_at') AND t.deleted_at IS NULL;\n",
		camel, sp.Table)
	return b.String()
}
