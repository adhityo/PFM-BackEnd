package main

import (
	"fmt"
	"sort"
	"strings"
)

// genSchema renders internal/db/schema/schema_gen.go: the table list and the
// reverse foreign-key map used for "still referenced" checks on soft delete.
func genSchema(s Schema) string {
	var b strings.Builder
	b.WriteString("// Code generated by cmd/scaffold; DO NOT EDIT.\n\n")
	b.WriteString("// Package schema describes the migrated database schema for runtime checks.\n")
	b.WriteString("package schema\n\n")
	b.WriteString("// Ref is a foreign key column of Table.\n")
	b.WriteString("type Ref struct {\n\tTable  string\n\tColumn string\n}\n\n")

	b.WriteString("// SoftDelete reports, for every table, whether it has a deleted_at column.\n")
	b.WriteString("var SoftDelete = map[string]bool{\n")
	for _, n := range s.names() {
		fmt.Fprintf(&b, "\t%q: %v,\n", n, s[n].SoftDelete)
	}
	b.WriteString("}\n\n")

	refs := map[string][]string{}
	for _, n := range s.names() {
		t := s[n]
		if !t.SoftDelete {
			continue // e.g. auth_refresh_token: lifecycle handled by its owner
		}
		cols := make([]string, 0, len(t.FKs))
		for c := range t.FKs {
			cols = append(cols, c)
		}
		sort.Strings(cols)
		for _, c := range cols {
			refs[t.FKs[c]] = append(refs[t.FKs[c]], fmt.Sprintf("{Table: %q, Column: %q}", n, c))
		}
	}
	b.WriteString("// ReferencedBy lists, per table, the soft-deletable rows that point at it.\n")
	b.WriteString("var ReferencedBy = map[string][]Ref{\n")
	parents := make([]string, 0, len(refs))
	for p := range refs {
		parents = append(parents, p)
	}
	sort.Strings(parents)
	for _, p := range parents {
		fmt.Fprintf(&b, "\t%q: {\n", p)
		for _, r := range refs[p] {
			fmt.Fprintf(&b, "\t\t%s,\n", r)
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	return b.String()
}
