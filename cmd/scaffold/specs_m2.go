// Tenant scope expressions (alias t) used by portfolio resources.
const (
	scopeViaPortfolio = "(SELECT sp.client_id FROM portfolio sp WHERE sp.id = t.portfolio_id)"
)

func scopeVia(parent, fk string) string {
	return "(SELECT sp.client_id FROM portfolio sp JOIN " + parent + " x ON x.portfolio_id = sp.id WHERE x.id = t." + fk + ")"
}

