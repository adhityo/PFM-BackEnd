CREATE TABLE portfolio (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                   UUID NOT NULL DEFAULT gen_random_uuid(),
    portfolio_name         VARCHAR(150),
    portfolio_code         VARCHAR(45),
    portfolio_date         DATE,
    portfolio_status       VARCHAR(45),
    description            TEXT,
    investment_manager_id  BIGINT,
    parent_portfolio_id    BIGINT,
    client_id              BIGINT,
    cash_fund_value        NUMERIC(20,4),
    cagr                   NUMERIC(12,6),
    fund_target_rate       NUMERIC(12,6),
    realized_profit_loss   NUMERIC(20,4),
    unrealized_profit_loss NUMERIC(20,4),
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by             VARCHAR(100),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by             VARCHAR(100),
    deleted_at             TIMESTAMPTZ,
    deleted_by             VARCHAR(100),
    CONSTRAINT uq_portfolio_uuid UNIQUE (uuid),
    CONSTRAINT fk_portfolio_investment_manager_id FOREIGN KEY (investment_manager_id) REFERENCES investment_manager (id),
    CONSTRAINT fk_portfolio_parent_portfolio_id FOREIGN KEY (parent_portfolio_id) REFERENCES portfolio (id),
    CONSTRAINT fk_portfolio_client_id FOREIGN KEY (client_id) REFERENCES client (id)
);
CREATE UNIQUE INDEX uq_portfolio_portfolio_code ON portfolio (portfolio_code) WHERE deleted_at IS NULL;
CREATE INDEX idx_portfolio_investment_manager_id ON portfolio (investment_manager_id);
CREATE INDEX idx_portfolio_parent_portfolio_id ON portfolio (parent_portfolio_id);
CREATE INDEX idx_portfolio_client_id ON portfolio (client_id);
CREATE TRIGGER trg_portfolio_updated_at BEFORE UPDATE ON portfolio
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
