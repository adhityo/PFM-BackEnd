CREATE TABLE app_user (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                 UUID NOT NULL DEFAULT gen_random_uuid(),
    description          VARCHAR(255),
    email                VARCHAR(255),
    first_name           VARCHAR(255),
    last_password_change TIMESTAMPTZ,
    password_changed     BOOLEAN NOT NULL DEFAULT FALSE,
    status               SMALLINT,
    username             VARCHAR(255),
    role_id              BIGINT,
    client_uuid          UUID,  -- client @ pfm_core (tanpa FK lintas database)
    is_supervisor        BOOLEAN NOT NULL DEFAULT FALSE,
    password_hash        VARCHAR(255),                 -- argon2id (PHC string)
    activation_key_hash  CHAR(64),                     -- sha256 hex
    activation_key_expires_at TIMESTAMPTZ,
    failed_login_count   SMALLINT NOT NULL DEFAULT 0,
    locked_until         TIMESTAMPTZ,
    last_login_at        TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by           VARCHAR(100),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by           VARCHAR(100),
    deleted_at           TIMESTAMPTZ,
    deleted_by           VARCHAR(100),
    CONSTRAINT uq_app_user_uuid UNIQUE (uuid),
    CONSTRAINT fk_app_user_role_id FOREIGN KEY (role_id) REFERENCES role (id)
);
CREATE UNIQUE INDEX uq_app_user_email ON app_user (email) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX uq_app_user_username ON app_user (username) WHERE deleted_at IS NULL;
CREATE INDEX idx_app_user_role_id ON app_user (role_id);
CREATE INDEX idx_app_user_client_uuid ON app_user (client_uuid);
CREATE TRIGGER trg_app_user_updated_at BEFORE UPDATE ON app_user
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
