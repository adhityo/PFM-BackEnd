-- +goose Up
-- +goose StatementBegin
CREATE TABLE auth_refresh_token (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid        UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id     BIGINT      NOT NULL,
    family_id   UUID        NOT NULL,           -- rotasi + deteksi reuse
    token_hash  CHAR(64)    NOT NULL,           -- sha256(token); token mentah tidak disimpan
    user_agent  VARCHAR(255),
    ip_address  INET,
    expires_at  TIMESTAMPTZ NOT NULL,
    revoked_at  TIMESTAMPTZ,
    replaced_by BIGINT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_auth_refresh_token_uuid UNIQUE (uuid),
    CONSTRAINT uq_auth_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_auth_refresh_token_user_id FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_auth_refresh_token_replaced_by FOREIGN KEY (replaced_by) REFERENCES auth_refresh_token (id)
);
CREATE INDEX idx_auth_refresh_token_user_id ON auth_refresh_token (user_id);
CREATE INDEX idx_auth_refresh_token_family_id ON auth_refresh_token (family_id);
CREATE INDEX idx_auth_refresh_token_replaced_by ON auth_refresh_token (replaced_by);
-- +goose StatementEnd

