CREATE TABLE sector (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                        UUID NOT NULL DEFAULT gen_random_uuid(),
    sector_name                 VARCHAR(150),
    sector_code                 VARCHAR(45),
    description                 TEXT,
    sector_status               SMALLINT,
    total_stock                 NUMERIC(24,8),
    total_market_capitalization NUMERIC(20,4),
    latest_sector_date          DATE,
    total_corporate             INTEGER,
    parent_sector_id            BIGINT,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by                  VARCHAR(100),
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by                  VARCHAR(100),
    deleted_at                  TIMESTAMPTZ,
    deleted_by                  VARCHAR(100),
    CONSTRAINT uq_sector_uuid UNIQUE (uuid),
    CONSTRAINT fk_sector_parent_sector_id FOREIGN KEY (parent_sector_id) REFERENCES sector (id)
);
CREATE UNIQUE INDEX uq_sector_sector_code ON sector (sector_code) WHERE deleted_at IS NULL;
CREATE INDEX idx_sector_parent_sector_id ON sector (parent_sector_id);
CREATE TRIGGER trg_sector_updated_at BEFORE UPDATE ON sector
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
