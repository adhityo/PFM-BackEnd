CREATE TABLE newsletter (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                   UUID NOT NULL DEFAULT gen_random_uuid(),
    description            VARCHAR(255),
    document_file_uuid     UUID,  -- file_object @ pfm_document (tanpa FK lintas database)
    email_template_file_uuid UUID,  -- file_object @ pfm_document (tanpa FK lintas database)
    newsletter_code        VARCHAR(255),
    newsletter_date        DATE,
    newsletter_name        VARCHAR(255),
    status                 SMALLINT,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by             VARCHAR(100),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by             VARCHAR(100),
    deleted_at             TIMESTAMPTZ,
    deleted_by             VARCHAR(100),
    CONSTRAINT uq_newsletter_uuid UNIQUE (uuid)
);
CREATE UNIQUE INDEX uq_newsletter_newsletter_code ON newsletter (newsletter_code) WHERE deleted_at IS NULL;
CREATE INDEX idx_newsletter_document_file_uuid ON newsletter (document_file_uuid);
CREATE INDEX idx_newsletter_email_template_file_uuid ON newsletter (email_template_file_uuid);
CREATE TRIGGER trg_newsletter_updated_at BEFORE UPDATE ON newsletter
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
