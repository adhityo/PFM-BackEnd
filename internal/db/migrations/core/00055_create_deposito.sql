CREATE TABLE deposito (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                 UUID NOT NULL DEFAULT gen_random_uuid(),
    deposito_name        VARCHAR(255),
    deposito_code        VARCHAR(45),
    description          TEXT,
    latest_interest_rate NUMERIC(12,6),
    tenor                INTEGER,
    bank_id              BIGINT,
    auto_rollover_status SMALLINT,
    bank_branch_name     VARCHAR(255),
    bank_name            VARCHAR(255),
    bilyet_number        VARCHAR(255),
    maturity_date        DATE,
    placement_date       DATE,
    placement_value      NUMERIC(20,4),
    status               VARCHAR(255),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by           VARCHAR(100),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by           VARCHAR(100),
    deleted_at           TIMESTAMPTZ,
    deleted_by           VARCHAR(100),
    CONSTRAINT uq_deposito_uuid UNIQUE (uuid),
    CONSTRAINT fk_deposito_bank_id FOREIGN KEY (bank_id) REFERENCES bank (id)
);
CREATE UNIQUE INDEX uq_deposito_deposito_code ON deposito (deposito_code) WHERE deleted_at IS NULL;
CREATE INDEX idx_deposito_bank_id ON deposito (bank_id);
CREATE TRIGGER trg_deposito_updated_at BEFORE UPDATE ON deposito
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
