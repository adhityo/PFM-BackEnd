CREATE TABLE bond_portfolio (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid              UUID NOT NULL DEFAULT gen_random_uuid(),
    bond_id           BIGINT,
    portfolio_id      BIGINT,
    nominal           NUMERIC(20,4),
    coupon            NUMERIC(12,6),
    maturity_date     DATE,
    status            SMALLINT,
    purchased_price   NUMERIC(20,4),
    yield_to_maturity NUMERIC(12,6),
    rating_id         BIGINT,
    accrued_interest  NUMERIC(20,4),
    bond_code         VARCHAR(255),
    bond_name         VARCHAR(255),
    market_value      NUMERIC(20,4),
    average_price     NUMERIC(20,4),
    bond_amount       NUMERIC(24,8),
    inception_date    DATE,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by        VARCHAR(100),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by        VARCHAR(100),
    deleted_at        TIMESTAMPTZ,
    deleted_by        VARCHAR(100),
    CONSTRAINT uq_bond_portfolio_uuid UNIQUE (uuid),
    CONSTRAINT fk_bond_portfolio_bond_id FOREIGN KEY (bond_id) REFERENCES bond (id),
