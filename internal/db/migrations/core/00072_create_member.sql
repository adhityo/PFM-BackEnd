CREATE TABLE member (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                        UUID NOT NULL DEFAULT gen_random_uuid(),
    member_name                 VARCHAR(255),
    member_number               VARCHAR(50),
    birthdate                   DATE,                         -- PII
    address                     TEXT,
    city_id                     BIGINT,
    province_id                 BIGINT,
    region_id                   BIGINT,
    country_id                  BIGINT,
    postal_code                 VARCHAR(45),
    email                       VARCHAR(255),
    telephone                   VARCHAR(45),
    mobile_phone                VARCHAR(45),                  -- PII
    faximile                    VARCHAR(45),
    description                 TEXT,
    bank_account_number         VARCHAR(45),                  -- PII
    bank_account_name           VARCHAR(45),
    bank_name                   VARCHAR(45),
    bank_branch_name            VARCHAR(45),
    bank_id                     BIGINT,
    identity_number             VARCHAR(255),                 -- PII
    latest_allowance            NUMERIC(20,4),
    latest_pension_premium      NUMERIC(20,4),
    latest_salary               NUMERIC(20,4),
    npwp                        VARCHAR(255),                 -- PII
    retired_date                DATE,
    start_working_date          DATE,
    occupation_id               BIGINT,
    pension_benefit_value       NUMERIC(20,4),
    family_status               VARCHAR(255),
    payment_method              SMALLINT,
    pension_number              VARCHAR(255),
    retirement_type             SMALLINT,
    sex                         VARCHAR(255),
    status                      SMALLINT,
    total_pension_premium_value NUMERIC(20,4),
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by                  VARCHAR(100),
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by                  VARCHAR(100),
    deleted_at                  TIMESTAMPTZ,
    deleted_by                  VARCHAR(100),
    CONSTRAINT uq_member_uuid UNIQUE (uuid),
    CONSTRAINT fk_member_city_id FOREIGN KEY (city_id) REFERENCES city (id),
    CONSTRAINT fk_member_province_id FOREIGN KEY (province_id) REFERENCES province (id),
    CONSTRAINT fk_member_country_id FOREIGN KEY (country_id) REFERENCES country (id),
    CONSTRAINT fk_member_bank_id FOREIGN KEY (bank_id) REFERENCES bank (id),
    CONSTRAINT fk_member_occupation_id FOREIGN KEY (occupation_id) REFERENCES occupation (id)
);
CREATE UNIQUE INDEX uq_member_member_number ON member (member_number) WHERE deleted_at IS NULL;
CREATE INDEX idx_member_city_id ON member (city_id);
CREATE INDEX idx_member_province_id ON member (province_id);
CREATE INDEX idx_member_country_id ON member (country_id);
CREATE INDEX idx_member_bank_id ON member (bank_id);
CREATE INDEX idx_member_occupation_id ON member (occupation_id);
CREATE TRIGGER trg_member_updated_at BEFORE UPDATE ON member
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
