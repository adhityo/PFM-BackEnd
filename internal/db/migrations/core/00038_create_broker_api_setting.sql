CREATE TABLE broker_api_setting (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                    UUID NOT NULL DEFAULT gen_random_uuid(),
    broker_name             VARCHAR(150),
    broker_id               BIGINT,
    broker_unique_code      VARCHAR(36),
    broker_api_setting_name VARCHAR(150),
    description             TEXT,
    status                  VARCHAR(50),
    protocol                VARCHAR(25),
    ip_address              INET,
    ip_address_list         CIDR[],
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by              VARCHAR(100),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by              VARCHAR(100),
    deleted_at              TIMESTAMPTZ,
    deleted_by              VARCHAR(100),
    CONSTRAINT uq_broker_api_setting_uuid UNIQUE (uuid),
    CONSTRAINT fk_broker_api_setting_broker_id FOREIGN KEY (broker_id) REFERENCES broker (id)
);
CREATE INDEX idx_broker_api_setting_broker_id ON broker_api_setting (broker_id);
CREATE TRIGGER trg_broker_api_setting_updated_at BEFORE UPDATE ON broker_api_setting
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
