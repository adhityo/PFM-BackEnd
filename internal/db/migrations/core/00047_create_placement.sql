CREATE TABLE placement (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                  UUID NOT NULL DEFAULT gen_random_uuid(),
    description           VARCHAR(255),
    end_date              DATE,
    placement_number      VARCHAR(255),
    placement_subject     VARCHAR(255),
    placement_value       NUMERIC(20,4),
    start_date            DATE,
    status                SMALLINT,
    investment_manager_id BIGINT,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by            VARCHAR(100),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by            VARCHAR(100),
    deleted_at            TIMESTAMPTZ,
    deleted_by            VARCHAR(100),
    CONSTRAINT uq_placement_uuid UNIQUE (uuid),
    CONSTRAINT fk_placement_investment_manager_id FOREIGN KEY (investment_manager_id) REFERENCES investment_manager (id)
);
CREATE INDEX idx_placement_investment_manager_id ON placement (investment_manager_id);
