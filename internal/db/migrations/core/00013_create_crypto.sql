CREATE TABLE crypto (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid        UUID NOT NULL DEFAULT gen_random_uuid(),
    description TEXT,
    status      VARCHAR(255),
    crypto_code VARCHAR(30),                  -- [USULAN] tabel legacy tidak punya kode
    crypto_name VARCHAR(255),                 -- [USULAN] tabel legacy tidak punya nama
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by  VARCHAR(100),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by  VARCHAR(100),
    deleted_at  TIMESTAMPTZ,
    deleted_by  VARCHAR(100),
    CONSTRAINT uq_crypto_uuid UNIQUE (uuid)
);
CREATE TRIGGER trg_crypto_updated_at BEFORE UPDATE ON crypto
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
