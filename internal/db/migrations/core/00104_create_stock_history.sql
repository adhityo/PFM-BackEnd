CREATE TABLE stock_history (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                         UUID NOT NULL DEFAULT gen_random_uuid(),
    stock_id                     BIGINT,
    stock_code                   VARCHAR(10),
    closing_date                 DATE,
    closing_price                NUMERIC(20,4),
    total_listed_share           NUMERIC(24,8),
    total_market_capitalization  NUMERIC(20,4),
    total_market_share           NUMERIC(24,8),
    stock_type_id                BIGINT,
    price_to_book_value          NUMERIC(20,4),
    price_earning_ratio          NUMERIC(12,6),
    fundamental_month            INTEGER,
    fundamental_year             INTEGER,
    stock_fundamental_history_id BIGINT,
    created_at                   TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by                   VARCHAR(100),
    updated_at                   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by                   VARCHAR(100),
    deleted_at                   TIMESTAMPTZ,
    deleted_by                   VARCHAR(100),
    CONSTRAINT uq_stock_history_uuid UNIQUE (uuid),
    CONSTRAINT fk_stock_history_stock_id FOREIGN KEY (stock_id) REFERENCES stock (id),
    CONSTRAINT fk_stock_history_stock_type_id FOREIGN KEY (stock_type_id) REFERENCES stock_type (id),
    CONSTRAINT fk_stock_history_stock_fundamental_history_id FOREIGN KEY (stock_fundamental_history_id) REFERENCES stock_fundamental_history (id)
);
