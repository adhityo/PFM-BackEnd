CREATE TABLE crypto_exchange (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                 UUID NOT NULL DEFAULT gen_random_uuid(),
    description          TEXT,
    status               VARCHAR(255),
    crypto_exchange_code VARCHAR(50),                  -- [USULAN]
    crypto_exchange_name VARCHAR(255),                 -- [USULAN]
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by           VARCHAR(100),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by           VARCHAR(100),
    deleted_at           TIMESTAMPTZ,
    deleted_by           VARCHAR(100),
    CONSTRAINT uq_crypto_exchange_uuid UNIQUE (uuid)
);
CREATE TRIGGER trg_crypto_exchange_updated_at BEFORE UPDATE ON crypto_exchange
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
