CREATE TABLE payment_document (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                        UUID NOT NULL DEFAULT gen_random_uuid(),
    description                 VARCHAR(255),
    document_name               VARCHAR(255),
    document_status             SMALLINT,
    document_file_uuid          UUID,  -- file_object @ pfm_document (tanpa FK lintas database)
    bond_coupon_schedule_id     BIGINT,
    document_category_id        BIGINT,
    investor_coupon_schedule_id BIGINT,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by                  VARCHAR(100),
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by                  VARCHAR(100),
    deleted_at                  TIMESTAMPTZ,
    deleted_by                  VARCHAR(100),
    CONSTRAINT uq_payment_document_uuid UNIQUE (uuid),
    CONSTRAINT fk_payment_document_bond_coupon_schedule_id FOREIGN KEY (bond_coupon_schedule_id) REFERENCES bond_coupon_schedule (id),
    CONSTRAINT fk_payment_document_document_category_id FOREIGN KEY (document_category_id) REFERENCES document_category (id),
    CONSTRAINT fk_payment_document_investor_coupon_schedule_id FOREIGN KEY (investor_coupon_schedule_id) REFERENCES investor_coupon_schedule (id)
);
