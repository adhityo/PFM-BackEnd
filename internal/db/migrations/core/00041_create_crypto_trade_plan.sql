CREATE TABLE crypto_trade_plan (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                 UUID NOT NULL DEFAULT gen_random_uuid(),
    crypto_exchange_name VARCHAR(255),
    crypto_pair_symbol   VARCHAR(255),
    description          TEXT,
    status               VARCHAR(255),
    crypto_exchange_id   BIGINT,
    crypto_id            BIGINT,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by           VARCHAR(100),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by           VARCHAR(100),
    deleted_at           TIMESTAMPTZ,
    deleted_by           VARCHAR(100),
    CONSTRAINT uq_crypto_trade_plan_uuid UNIQUE (uuid),
    CONSTRAINT fk_crypto_trade_plan_crypto_exchange_id FOREIGN KEY (crypto_exchange_id) REFERENCES crypto_exchange (id),
    CONSTRAINT fk_crypto_trade_plan_crypto_id FOREIGN KEY (crypto_id) REFERENCES crypto (id)
);
CREATE INDEX idx_crypto_trade_plan_crypto_exchange_id ON crypto_trade_plan (crypto_exchange_id);
CREATE INDEX idx_crypto_trade_plan_crypto_id ON crypto_trade_plan (crypto_id);
CREATE TRIGGER trg_crypto_trade_plan_updated_at BEFORE UPDATE ON crypto_trade_plan
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
