CREATE TABLE emitent (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid            UUID NOT NULL DEFAULT gen_random_uuid(),
    address         VARCHAR(255),
    description     VARCHAR(255),
    email           VARCHAR(255),
    emitent_name    VARCHAR(255),
    faximile        VARCHAR(255),
    npwp            VARCHAR(255),                 -- PII
    sector_name     VARCHAR(255),
    status          SMALLINT,
    sub_sector_name VARCHAR(255),
    telephone       VARCHAR(255),
    sector_id       BIGINT,
    sub_sector_id   BIGINT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by      VARCHAR(100),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by      VARCHAR(100),
    deleted_at      TIMESTAMPTZ,
    deleted_by      VARCHAR(100),
    CONSTRAINT uq_emitent_uuid UNIQUE (uuid),
    CONSTRAINT fk_emitent_sector_id FOREIGN KEY (sector_id) REFERENCES sector (id),
