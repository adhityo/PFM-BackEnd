-- Antrean email (pfm_core, pfm_security, pfm_document). Email ditulis di transaksi bisnis yang sama,
-- lalu worker mengirimnya lewat SMTP di luar transaksi, dengan percobaan ulang bertahap. Baris
-- dihapus setelah terkirim; setelah gagal berulang, isi email (berisi tautan rahasia) dikosongkan.
-- Role aplikasi hanya boleh INSERT.
-- +goose Up
-- +goose StatementBegin
CREATE TABLE mail_outbox (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid            UUID NOT NULL,
    recipient       VARCHAR(254) NOT NULL,
    subject         VARCHAR(255) NOT NULL,
    body_text       TEXT NOT NULL,
    body_html       TEXT,
    attempts        SMALLINT NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_error      VARCHAR(500),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_mail_outbox_uuid UNIQUE (uuid)
);
CREATE INDEX idx_mail_outbox_next_attempt_at ON mail_outbox (next_attempt_at);
-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin
DROP TABLE IF EXISTS mail_outbox;
-- +goose StatementEnd
