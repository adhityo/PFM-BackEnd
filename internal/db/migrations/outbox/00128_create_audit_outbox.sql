-- Outbox audit: dipasang di pfm_core, pfm_security dan pfm_document. Event audit ditulis di
-- transaksi bisnis yang sama (atomik), lalu worker memindahkannya ke pfm_log.activity_log
-- (idempoten lewat uuid) dan menghapusnya dari outbox. Role aplikasi hanya boleh INSERT.
-- +goose Up
-- +goose StatementBegin
CREATE TABLE audit_outbox (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid             UUID NOT NULL,
    action_query     VARCHAR(255),
    ip_address       INET,
    log_action       VARCHAR(255),
    log_description  VARCHAR(255),
    log_session_code VARCHAR(255),
    log_time         TIMESTAMPTZ NOT NULL DEFAULT now(),
    log_title        VARCHAR(255),
    role_code        VARCHAR(255),
    username         VARCHAR(255),
    source           VARCHAR(20) NOT NULL,
    CONSTRAINT uq_audit_outbox_uuid UNIQUE (uuid)
);
-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin
DROP TABLE IF EXISTS audit_outbox;
-- +goose StatementEnd
