CREATE TABLE finance_transaction (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                 UUID NOT NULL DEFAULT gen_random_uuid(),
    stock_trade_id       BIGINT,
    bond_trade_id        BIGINT,
    mutual_fund_trade_id BIGINT,
    deposito_trade_id    BIGINT,
    transaction_date     DATE,
    transaction_number   VARCHAR(255),
    transaction_value    NUMERIC(20,4),
    description          TEXT,
    transaction_status   SMALLINT,
    portfolio_id         BIGINT,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by           VARCHAR(100),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by           VARCHAR(100),
    deleted_at           TIMESTAMPTZ,
    deleted_by           VARCHAR(100),
    CONSTRAINT uq_finance_transaction_uuid UNIQUE (uuid),
    CONSTRAINT fk_finance_transaction_stock_trade_id FOREIGN KEY (stock_trade_id) REFERENCES stock_trade (id),
    CONSTRAINT fk_finance_transaction_bond_trade_id FOREIGN KEY (bond_trade_id) REFERENCES bond_trade (id),
    CONSTRAINT fk_finance_transaction_mutual_fund_trade_id FOREIGN KEY (mutual_fund_trade_id) REFERENCES mutual_fund_trade (id),
    CONSTRAINT fk_finance_transaction_portfolio_id FOREIGN KEY (portfolio_id) REFERENCES portfolio (id)
);
CREATE INDEX idx_finance_transaction_stock_trade_id ON finance_transaction (stock_trade_id);
CREATE INDEX idx_finance_transaction_bond_trade_id ON finance_transaction (bond_trade_id);
CREATE INDEX idx_finance_transaction_mutual_fund_trade_id ON finance_transaction (mutual_fund_trade_id);
CREATE INDEX idx_finance_transaction_portfolio_id ON finance_transaction (portfolio_id);
CREATE TRIGGER trg_finance_transaction_updated_at BEFORE UPDATE ON finance_transaction
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
