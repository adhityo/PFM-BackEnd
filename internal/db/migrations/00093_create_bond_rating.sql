CREATE TABLE bond_rating (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid               UUID NOT NULL DEFAULT gen_random_uuid(),
    bond_id            BIGINT,
    rating_id          BIGINT,
    rating_agency_id   BIGINT,
    description        TEXT,
    rating_date        DATE,
    bond_name          VARCHAR(255),
    rating_agency_name VARCHAR(255),
    rating_value       VARCHAR(255),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by         VARCHAR(100),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by         VARCHAR(100),
    deleted_at         TIMESTAMPTZ,
    deleted_by         VARCHAR(100),
    CONSTRAINT uq_bond_rating_uuid UNIQUE (uuid),
    CONSTRAINT fk_bond_rating_bond_id FOREIGN KEY (bond_id) REFERENCES bond (id),
    CONSTRAINT fk_bond_rating_rating_id FOREIGN KEY (rating_id) REFERENCES rating (id),
    CONSTRAINT fk_bond_rating_rating_agency_id FOREIGN KEY (rating_agency_id) REFERENCES rating_agency (id)
);
