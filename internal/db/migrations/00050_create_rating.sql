CREATE TABLE rating (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid             UUID NOT NULL DEFAULT gen_random_uuid(),
    rating_name      VARCHAR(255),
    rating_code      VARCHAR(50),
    description      TEXT,
    rating_agency_id BIGINT,
    status           SMALLINT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by       VARCHAR(100),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by       VARCHAR(100),
    deleted_at       TIMESTAMPTZ,
    deleted_by       VARCHAR(100),
    CONSTRAINT uq_rating_uuid UNIQUE (uuid),
    CONSTRAINT fk_rating_rating_agency_id FOREIGN KEY (rating_agency_id) REFERENCES rating_agency (id)
);
CREATE UNIQUE INDEX uq_rating_rating_code ON rating (rating_code) WHERE deleted_at IS NULL;
