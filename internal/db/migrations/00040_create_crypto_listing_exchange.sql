CREATE TABLE crypto_listing_exchange (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                        UUID NOT NULL DEFAULT gen_random_uuid(),
    crypto_exchange_name        VARCHAR(255),
    crypto_exchange_unique_code VARCHAR(255),
    description                 TEXT,
    status                      VARCHAR(255),
    crypto_exchange_id          BIGINT,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by                  VARCHAR(100),
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by                  VARCHAR(100),
    deleted_at                  TIMESTAMPTZ,
    deleted_by                  VARCHAR(100),
    CONSTRAINT uq_crypto_listing_exchange_uuid UNIQUE (uuid),
    CONSTRAINT fk_crypto_listing_exchange_crypto_exchange_id FOREIGN KEY (crypto_exchange_id) REFERENCES crypto_exchange (id)
);
CREATE INDEX idx_crypto_listing_exchange_crypto_exchange_id ON crypto_listing_exchange (crypto_exchange_id);
CREATE TRIGGER trg_crypto_listing_exchange_updated_at BEFORE UPDATE ON crypto_listing_exchange
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
