--  * number_sequence: penomoran tanpa celah (jurnal, dst.) di dalam transaksi pemakai nomor.
--  * crypto_trade.portfolio_id [USULAN]: posisi kripto butuh portofolio (legacy tidak punya).
--  * finance_transaction: tautan ke trade kripto, cash settlement, dan jurnal yang dibalik.
--  * status default draft (0) untuk transaksi, posted (1) untuk jurnal.
--  * unique index posisi & mapping akun agar lookup tidak ambigu.
