CREATE TABLE crypto_trade (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                   UUID NOT NULL DEFAULT gen_random_uuid(),
    crypto_code            VARCHAR(255),
    crypto_name            VARCHAR(255),
    description            TEXT,
    price                  NUMERIC(28,8),
    quantity               NUMERIC(28,8),
    risk_classification    VARCHAR(255),
    status                 VARCHAR(255),
    trade_date             DATE,
    trade_time             TIMESTAMPTZ,
    trade_type_name        VARCHAR(255),
    trade_value            NUMERIC(28,8),
    transaction_fee_amount NUMERIC(28,8),
    crypto_id              BIGINT,
    crypto_trade_plan_id   BIGINT,
    trade_type_id          BIGINT,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by             VARCHAR(100),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by             VARCHAR(100),
    deleted_at             TIMESTAMPTZ,
    deleted_by             VARCHAR(100),
    CONSTRAINT uq_crypto_trade_uuid UNIQUE (uuid),
    CONSTRAINT fk_crypto_trade_crypto_id FOREIGN KEY (crypto_id) REFERENCES crypto (id),
    CONSTRAINT fk_crypto_trade_crypto_trade_plan_id FOREIGN KEY (crypto_trade_plan_id) REFERENCES crypto_trade_plan (id),
    CONSTRAINT fk_crypto_trade_trade_type_id FOREIGN KEY (trade_type_id) REFERENCES trade_type (id)
);
CREATE INDEX idx_crypto_trade_crypto_id ON crypto_trade (crypto_id);
CREATE INDEX idx_crypto_trade_crypto_trade_plan_id ON crypto_trade (crypto_trade_plan_id);
CREATE INDEX idx_crypto_trade_trade_type_id ON crypto_trade (trade_type_id);
CREATE TRIGGER trg_crypto_trade_updated_at BEFORE UPDATE ON crypto_trade
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
