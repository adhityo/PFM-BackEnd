CREATE TABLE notification (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                UUID NOT NULL DEFAULT gen_random_uuid(),
    message             VARCHAR(255),
    recipient_email     VARCHAR(255),
    recipient_handphone VARCHAR(255),                 -- PII
    recipient_name      VARCHAR(255),
    recipient_type      VARCHAR(255),
    reference_id        VARCHAR(255),
    status              SMALLINT,
    total_counter       INTEGER,
    newsletter_id       BIGINT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          VARCHAR(100),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          VARCHAR(100),
    deleted_at          TIMESTAMPTZ,
    deleted_by          VARCHAR(100),
    CONSTRAINT uq_notification_uuid UNIQUE (uuid),
    CONSTRAINT fk_notification_newsletter_id FOREIGN KEY (newsletter_id) REFERENCES newsletter (id)
);
CREATE INDEX idx_notification_newsletter_id ON notification (newsletter_id);
CREATE TRIGGER trg_notification_updated_at BEFORE UPDATE ON notification
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
