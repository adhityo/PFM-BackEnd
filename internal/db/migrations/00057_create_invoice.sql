CREATE TABLE invoice (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                UUID NOT NULL DEFAULT gen_random_uuid(),
    billing_description VARCHAR(255),
    description         VARCHAR(255),
    invoice_date        DATE,
    invoice_due_date    DATE,
    invoice_number      VARCHAR(255),
    invoice_status      SMALLINT,
    invoice_tax_value   NUMERIC(20,4),
    invoice_total_value NUMERIC(20,4),
    invoice_value       NUMERIC(20,4),
    month               INTEGER,
    total_member        INTEGER,
    year                INTEGER,
    client_id           BIGINT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          VARCHAR(100),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          VARCHAR(100),
    deleted_at          TIMESTAMPTZ,
    deleted_by          VARCHAR(100),
    CONSTRAINT uq_invoice_uuid UNIQUE (uuid),
    CONSTRAINT fk_invoice_client_id FOREIGN KEY (client_id) REFERENCES client (id)
);
CREATE UNIQUE INDEX uq_invoice_invoice_number ON invoice (invoice_number) WHERE deleted_at IS NULL;
CREATE INDEX idx_invoice_client_id ON invoice (client_id);
CREATE TRIGGER trg_invoice_updated_at BEFORE UPDATE ON invoice
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
