CREATE TABLE crypto_portfolio (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                  UUID NOT NULL DEFAULT gen_random_uuid(),
    description           TEXT,
    status                VARCHAR(255),
    total_average_price   NUMERIC(28,8),
    total_crypto_quantity NUMERIC(28,8),
    total_value           NUMERIC(28,8),
    portfolio_id          BIGINT,                       -- [USULAN] relasi ke portfolio
    crypto_id             BIGINT,                       -- [USULAN] relasi ke crypto
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by            VARCHAR(100),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by            VARCHAR(100),
    deleted_at            TIMESTAMPTZ,
    deleted_by            VARCHAR(100),
    CONSTRAINT uq_crypto_portfolio_uuid UNIQUE (uuid),
    CONSTRAINT fk_crypto_portfolio_portfolio_id FOREIGN KEY (portfolio_id) REFERENCES portfolio (id),
    CONSTRAINT fk_crypto_portfolio_crypto_id FOREIGN KEY (crypto_id) REFERENCES crypto (id)
);
CREATE INDEX idx_crypto_portfolio_portfolio_id ON crypto_portfolio (portfolio_id);
CREATE INDEX idx_crypto_portfolio_crypto_id ON crypto_portfolio (crypto_id);
CREATE TRIGGER trg_crypto_portfolio_updated_at BEFORE UPDATE ON crypto_portfolio
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
-- +goose StatementEnd

